/* VISUTRA — order sheet helpers: photo resize + PDF with photo / SKU / description / qty per item.
   Needs window.vtStatement.ensurePdf (statement-share.js) for jsPDF. */
(function(){
  'use strict';
  var MAX = 560, QUALITY = 0.72;
  function resizeImage(file){
    return new Promise(function(res, rej){
      if(!file || !/^image\//.test(file.type || '')) return rej(new Error('Please choose an image file (JPG or PNG).'));
      var url = URL.createObjectURL(file), img = new Image();
      img.onload = function(){
        try{
          var w = img.naturalWidth, h = img.naturalHeight, k = Math.min(1, MAX / Math.max(w, h));
          var cw = Math.max(1, Math.round(w * k)), ch = Math.max(1, Math.round(h * k));
          var c = document.createElement('canvas'); c.width = cw; c.height = ch;
          var ctx = c.getContext('2d'); ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, cw, ch); ctx.drawImage(img, 0, 0, cw, ch);
          URL.revokeObjectURL(url);
          res({ data: c.toDataURL('image/jpeg', QUALITY), w: cw, h: ch });
        }catch(e){ rej(e); }
      };
      img.onerror = function(){ URL.revokeObjectURL(url); rej(new Error('This photo could not be read (HEIC photos: take a JPG or screenshot instead).')); };
      img.src = url;
    });
  }
  function fit(w, h, bw, bh){ if(!w || !h) return { w: bw, h: bh }; var k = Math.min(bw / w, bh / h); return { w: w * k, h: h * k }; }
  function dmy(){ var d = new Date(); return ('0' + d.getDate()).slice(-2) + '-' + ('0' + (d.getMonth() + 1)).slice(-2) + '-' + d.getFullYear(); }
  /* o: { ownerName, orderNo, toName, note, lines:[{sku,name,description,unit,qty,imageData,imgW,imgH}] } */
  function makePdf(o){
    return window.vtStatement.ensurePdf().then(function(){
      var J = window.jspdf.jsPDF, doc = new J({ unit: 'pt', format: 'a4' }), W = 595, H = 842, M = 36, ROW = 112, GAP = 8;
      var y = 0, page = 1, totalQty = 0;
      function header(first){
        doc.setTextColor(0); doc.setFont('helvetica', 'bold'); doc.setFontSize(16); doc.text(o.ownerName || 'VISUTRA', M, 42);
        doc.setFontSize(11); doc.setTextColor(224, 83, 26); doc.text('ORDER SHEET', W - M, 42, { align: 'right' });
        doc.setTextColor(90); doc.setFont('helvetica', 'normal'); doc.setFontSize(10);
        doc.text('Order no: ' + o.orderNo + '    Date: ' + dmy(), M, 60);
        doc.text('To: ' + (o.toName || ''), M, 74);
        y = 86;
        if(first && o.note){ var nl = doc.splitTextToSize('Note: ' + o.note, W - 2 * M); doc.text(nl.slice(0, 3), M, y + 8); y += 8 + Math.min(3, nl.length) * 12; }
        doc.setDrawColor(224, 83, 26); doc.setLineWidth(1.2); doc.line(M, y + 4, W - M, y + 4); y += 14;
      }
      function footer(){
        var n = doc.getNumberOfPages();
        for(var i = 1; i <= n; i++){ doc.setPage(i); doc.setFontSize(8); doc.setTextColor(130); doc.text('Generated by VISUTRA (visutra.in)', M, H - 18); doc.text('Page ' + i + ' of ' + n, W - M, H - 18, { align: 'right' }); }
      }
      header(true);
      if(o.layout === 'table'){
        var RH = 38, PS = 32;
        doc.autoTable({
          startY: y, margin: { left: M, right: M, top: 96, bottom: 40 }, theme: 'grid',
          styles: { fontSize: 8.5, cellPadding: { top: 3, bottom: 3, left: 4, right: 4 }, minCellHeight: RH, valign: 'middle', lineColor: [215, 215, 215] },
          headStyles: { fillColor: [224, 83, 26], textColor: 255, minCellHeight: 20, fontSize: 8.5 },
          head: [['#', 'Photo', 'SKU', 'Product / description', 'Qty', 'Unit']],
          body: o.lines.map(function(l, i){ totalQty += Number(l.qty) || 0; var d = (l.description || '').replace(/\s+/g, ' '); if(d.length > 110) d = d.slice(0, 107) + '...'; return [String(i + 1), '', l.sku || '', (l.name || '') + (d ? '\n' + d : ''), String(l.qty), l.unit || 'PCS']; }),
          columnStyles: { 0: { cellWidth: 22, halign: 'center' }, 1: { cellWidth: PS + 10 }, 2: { cellWidth: 80, fontStyle: 'bold', textColor: [224, 83, 26] }, 3: { cellWidth: 'auto' }, 4: { cellWidth: 44, halign: 'center', fontStyle: 'bold', fontSize: 12 }, 5: { cellWidth: 36, halign: 'center' } },
          didDrawCell: function(d){
            if(d.section === 'body' && d.column.index === 1){
              var l = o.lines[d.row.index]; if(!l || !l.imageData) return;
              try{ var f = fit(l.imgW, l.imgH, PS, PS); doc.addImage(l.imageData, 'JPEG', d.cell.x + (d.cell.width - f.w) / 2, d.cell.y + (d.cell.height - f.h) / 2, f.w, f.h); }catch(e){}
            }
          },
          didDrawPage: function(d){ if(d.pageNumber > 1) header(false); }
        });
        y = doc.lastAutoTable.finalY + 22;
        if(y > H - 50){ doc.addPage(); y = 60; }
        doc.setFont('helvetica', 'bold'); doc.setFontSize(12); doc.setTextColor(0);
        doc.text('Total items: ' + o.lines.length + '     Total quantity: ' + totalQty, W - M, y, { align: 'right' });
        footer();
        return { blob: doc.output('blob'), totalQty: totalQty, name: 'Order-' + o.orderNo + '.pdf' };
      }
      o.lines.forEach(function(l, idx){
        if(y + ROW > H - 80){ doc.addPage(); page++; header(false); }
        totalQty += Number(l.qty) || 0;
        doc.setDrawColor(215); doc.setLineWidth(0.7); doc.roundedRect(M, y, W - 2 * M, ROW - GAP, 6, 6);
        // photo box 96x96
        var bx = M + 8, by = y + 6, bs = ROW - GAP - 12;
        doc.setDrawColor(230); doc.rect(bx, by, bs, bs);
        if(l.imageData){
          try{ var f = fit(l.imgW, l.imgH, bs - 2, bs - 2); doc.addImage(l.imageData, 'JPEG', bx + 1 + (bs - 2 - f.w) / 2, by + 1 + (bs - 2 - f.h) / 2, f.w, f.h); }catch(e){}
        } else { doc.setFontSize(8); doc.setTextColor(150); doc.text('No photo', bx + bs / 2, by + bs / 2, { align: 'center' }); }
        var tx = bx + bs + 12, tw = W - M - 96 - tx;
        doc.setFont('helvetica', 'bold'); doc.setFontSize(11); doc.setTextColor(224, 83, 26); doc.text('SKU: ' + (l.sku || ''), tx, y + 20);
        doc.setTextColor(0); doc.setFontSize(10.5); doc.text(doc.splitTextToSize(l.name || '', tw).slice(0, 2), tx, y + 36);
        doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(80);
        var nameLines = Math.min(2, doc.splitTextToSize(l.name || '', tw).length);
        doc.text(doc.splitTextToSize(l.description || '', tw).slice(0, nameLines === 2 ? 3 : 4), tx, y + 36 + nameLines * 12 + 2);
        // qty box
        var qx = W - M - 84;
        doc.setDrawColor(224, 83, 26); doc.setFillColor(255, 244, 236); doc.roundedRect(qx, y + 18, 76, ROW - GAP - 36, 6, 6, 'FD');
        doc.setFontSize(8); doc.setTextColor(120); doc.text('QTY', qx + 38, y + 32, { align: 'center' });
        doc.setFont('helvetica', 'bold'); doc.setFontSize(20); doc.setTextColor(0); doc.text(String(l.qty), qx + 38, y + 58, { align: 'center' });
        doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(90); doc.text(l.unit || 'PCS', qx + 38, y + 72, { align: 'center' });
        y += ROW;
      });
      if(y + 40 > H - 40){ doc.addPage(); header(false); }
      doc.setFont('helvetica', 'bold'); doc.setFontSize(12); doc.setTextColor(0);
      doc.text('Total items: ' + o.lines.length + '     Total quantity: ' + totalQty, W - M, y + 14, { align: 'right' });
      footer();
      return { blob: doc.output('blob'), totalQty: totalQty, name: 'Order-' + o.orderNo + '.pdf' };
    });
  }
  window.OSHEET = { resizeImage: resizeImage, makePdf: makePdf };
})();
